import { expect, test } from "@playwright/test";
import { accounts, signInReady, tickets } from "../lab-03/helpers";
import { contrastViolations, expectVisibleFocus, structureViolations } from "../lab-03/layout";

test("Lab 4 dashboards and Action forms have semantic names, contrast, focus, and keyboard-operable dialogs", async ({ page }) => {
  await signInReady(page, accounts.narin.email);
  await page.goto("/dashboard");
  await expect(page.getByRole("heading", { name: "Dashboard" })).toBeVisible();
  expect(await structureViolations(page)).toEqual([]);
  expect(await contrastViolations(page)).toEqual([]);
  await page.getByRole("link", { name: "View my active actions" }).focus();
  await expectVisibleFocus(page, "Staff dashboard drill-down");
  await page.goto(`/staff/tickets/${tickets.maliOpen.id}`);
  await expect(page.getByRole("heading", { name: tickets.maliOpen.number })).toBeVisible();
  expect(await structureViolations(page)).toEqual([]);
  await page.getByRole("button", { name: "Add action" }).focus();
  await expectVisibleFocus(page, "Add action");
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog", { name: "Add action" });
  await expect(dialog).toBeVisible();
  expect(await structureViolations(page)).toEqual([]);
  expect(await contrastViolations(page)).toEqual([]);
  await dialog.getByLabel("Follow-Up Required").check();
  await dialog.getByRole("button", { name: "Add action" }).click();
  await expect(dialog.getByLabel("Action Description")).toBeFocused();
  await dialog.getByLabel("Action Description").fill("Check the route");
  await dialog.getByRole("button", { name: "Add action" }).click();
  const note = dialog.getByLabel("Follow-Up Note");
  await expect(note).toBeFocused();
  await expect(note).toHaveAccessibleDescription("Follow-Up Note is required when follow-up is selected.");
  expect(await structureViolations(page)).toEqual([]);
  page.once("dialog", async (confirmation) => confirmation.accept());
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Add action" })).toBeFocused();
  const action = page.locator("#action-34a00000-0000-4000-8000-000000000002");
  await action.getByRole("button", { name: "View action" }).click();
  await expect(action).toContainText("Follow-up: Required");
  await action.getByRole("button", { name: "Reassign" }).click();
  const assignment = page.getByRole("dialog", { name: "Assign action" });
  await expect(assignment).toBeVisible();
  await page.keyboard.press("Tab");
  await expect(assignment).toContainText("Assigned to");
  await page.keyboard.press("Escape");
  await expect(assignment).toHaveCount(0);
});
