import { expect, test } from "@playwright/test";
import { accounts, apiSession, apiUrl, csrfHeaders, openMenuIfCollapsed, signInReady } from "../lab-03/helpers";
import { actions, createAction, freshTicket, screenshot, staffTicket } from "./helpers";

test.describe("E2E-01 Actions Taken", () => {
  test("requires a follow-up note, keeps the draft after a safe failure, and prevents repeated creation", async ({ page, request }) => {
    const ticket = await freshTicket(request, "Follow-up action");
    await signInReady(page, accounts.narin.email);
    await page.goto(`/staff/tickets/${ticket.id}`);
    await page.getByRole("button", { name: "Claim ticket" }).click();
    await expect(page.getByText("You now own this Ticket.")).toBeVisible();
    await page.getByRole("button", { name: "Add action" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel("Action Description").fill("Check the VPN route");
    await dialog.getByLabel("Result").fill("Route restored");
    await dialog.getByLabel("Assigned to").selectOption({ label: accounts.narin.name });
    await dialog.getByLabel("Follow-Up Required").check();
    await dialog.getByRole("button", { name: "Add action" }).click();
    await expect(dialog.getByText("Follow-Up Note is required when follow-up is selected.")).toBeVisible();
    await expect(dialog.getByLabel("Follow-Up Note")).toBeFocused();
    expect(await actions(page, ticket.id)).toHaveLength(0);
    await dialog.getByLabel("Follow-Up Note").fill("Ask the Requester to retry tomorrow.");
    await screenshot(page, "actions-taken", "follow-up-validation-and-draft");
    await page.route(`**/api/tickets/${ticket.id}/actions`, async (route) => route.request().method() === "POST" ? route.fulfill({ status: 503, json: { error: { code: "DEPENDENCY_UNAVAILABLE", message: "Service unavailable." } } }) : route.continue());
    await dialog.getByRole("button", { name: "Add action" }).click();
    await expect(dialog.getByRole("alert")).toContainText("Your entries are kept");
    await expect(dialog.getByLabel("Action Description")).toHaveValue("Check the VPN route");
    await expect(dialog.getByLabel("Follow-Up Note")).toHaveValue("Ask the Requester to retry tomorrow.");
    expect(await actions(page, ticket.id)).toHaveLength(0);
    await screenshot(page, "actions-taken", "server-failure-draft-retained");
    await page.unroute(`**/api/tickets/${ticket.id}/actions`);
    let posts = 0;
    await page.route(`**/api/tickets/${ticket.id}/actions`, async (route) => { if (route.request().method() === "POST") posts += 1; await route.continue(); });
    await dialog.getByRole("button", { name: "Add action" }).evaluate((button) => { (button as HTMLButtonElement).click(); (button as HTMLButtonElement).click(); });
    await expect(page.getByRole("status").filter({ hasText: "Action saved." })).toBeVisible();
    expect(posts).toBe(1);
    expect(await actions(page, ticket.id)).toHaveLength(1);
    await screenshot(page, "actions-taken", "created-follow-up");
  });

  test("assigns, edits, starts, completes and cancels separate actions, then shows Requester read-only data", async ({ page, request }) => {
    const ticket = await freshTicket(request, "Action lifecycle");
    await signInReady(page, accounts.narin.email);
    await page.goto(`/staff/tickets/${ticket.id}`);
    await page.getByRole("button", { name: "Claim ticket" }).click();
    await expect(page.getByText("You now own this Ticket.")).toBeVisible();
    const first = await createAction(page, ticket.id, "Inspect service", "Diagnostics complete");
    await page.reload();
    const row = page.locator(`#action-${first.id}`);
    await row.getByRole("button", { name: "View action" }).click();
    await row.getByRole("button", { name: "Assign", exact: true }).click();
    await page.getByRole("dialog").getByLabel("Assigned to").selectOption({ label: accounts.kanda.name });
    await screenshot(page, "actions-taken", "assign-mode");
    await page.getByRole("dialog").getByRole("button", { name: "Save assignment" }).click();
    await expect(row).toContainText(`Assigned to ${accounts.kanda.name}`);
    await row.getByRole("button", { name: "Edit action" }).click();
    await page.getByRole("dialog").getByLabel("Result").fill("Diagnostics and repair complete");
    await screenshot(page, "actions-taken", "edit-mode");
    await page.getByRole("dialog").getByRole("button", { name: "Save action" }).click();
    await expect(row).toContainText("Inspect service");
    await row.getByRole("button", { name: "Start", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Confirm" }).click();
    await expect(row).toContainText("IN PROGRESS");
    await row.getByRole("button", { name: "Complete", exact: true }).click();
    await page.getByRole("dialog").getByRole("button", { name: "Confirm" }).click();
    await expect(row).toContainText("COMPLETED");
    await expect(row.getByRole("button", { name: "Edit action" })).toHaveCount(0);
    await screenshot(page, "actions-taken", "completed-read-only");
    const second = await createAction(page, ticket.id, "Duplicate diagnostic", "Superseded");
    await page.reload();
    const secondRow = page.locator(`#action-${second.id}`);
    await secondRow.getByRole("button", { name: "View action" }).click();
    await secondRow.getByRole("button", { name: "Cancel action" }).click();
    const cancel = page.getByRole("dialog");
    await cancel.getByRole("button", { name: "Confirm" }).click();
    await expect(cancel.getByText(/Enter a cancellation reason/)).toBeVisible();
    await cancel.getByLabel("Cancellation reason").fill("Duplicate work item");
    await cancel.getByRole("button", { name: "Confirm" }).click();
    await expect(secondRow).toContainText("CANCELLED");
    await screenshot(page, "actions-taken", "cancelled-read-only");
    await openMenuIfCollapsed(page);
    await page.getByRole("button", { name: "Logout" }).click();
    await signInReady(page, accounts.anan.email);
    await page.goto(`/tickets/${ticket.id}`);
    await expect(page.getByRole("heading", { name: ticket.summary })).toBeVisible();
    await expect(page.locator(".actions-list li")).toHaveCount(2);
    await expect(page.getByRole("button", { name: "Add action" })).toHaveCount(0);
    await page.locator(`#action-${first.id}`).getByRole("button", { name: "View action" }).click();
    await expect(page.locator(`#action-${first.id}`)).toContainText("Diagnostics and repair complete");
    await expect(page.getByText("Internal Notes")).toHaveCount(0);
    await screenshot(page, "actions-taken", "requester-read-only");
  });

  test("rejects an inactive assignee without mutation and preserves an edit draft after a stale collision", async ({ page, request }) => {
    const ticket = await freshTicket(request, "Action conflict");
    await apiSession(request, accounts.araya.email);
    const usersResponse = await request.get(`${apiUrl}/api/admin/users?search=wichai.inactive.staff`);
    expect(usersResponse.status()).toBe(200);
    const inactiveId = (await usersResponse.json()).data[0].id as number;
    await signInReady(page, accounts.narin.email);
    // Simulate an assignee list cached just before deactivation; the real write API must still reject it.
    await page.route("**/api/staff/assignees", async (route) => { const response = await route.fetch(); const payload = await response.json(); payload.data.push({ id: inactiveId, displayName: "Wichai Support", role: "IT_STAFF" }); await route.fulfill({ response, json: payload }); });
    await page.goto(`/staff/tickets/${ticket.id}`);
    await page.getByRole("button", { name: "Claim ticket" }).click();
    await expect(page.getByText("You now own this Ticket.")).toBeVisible();
    const action = await createAction(page, ticket.id, "Review the logs");
    const before = await actions(page, ticket.id);
    const invalid = await page.request.patch(`${apiUrl}/api/tickets/${ticket.id}/actions/${action.id}/assignee`, { headers: await csrfHeaders(page), data: { ticketVersion: before[0].ticketVersion, actionVersion: before[0].version, assigneeId: inactiveId } });
    expect(invalid.status()).toBe(422);
    expect((await invalid.json()).error.code).toBe("INACTIVE_ASSIGNEE");
    expect(await actions(page, ticket.id)).toEqual(before);
    await page.reload();
    const row = page.locator(`#action-${action.id}`);
    await row.getByRole("button", { name: "View action" }).click();
    await row.getByRole("button", { name: "Assign", exact: true }).click();
    await page.getByRole("dialog").getByLabel("Assigned to").selectOption({ label: "Wichai Support" });
    await page.getByRole("dialog").getByRole("button", { name: "Save assignment" }).click();
    await expect(page.getByRole("dialog").getByText("The selected assignee is inactive.", { exact: true })).toBeVisible();
    expect(await actions(page, ticket.id)).toEqual(before);
    await screenshot(page, "actions-taken", "inactive-assignee-rejected");
    page.once("dialog", async (confirmation) => confirmation.accept());
    await page.getByRole("dialog").getByRole("button", { name: "Close" }).click();
    await row.getByRole("button", { name: "Edit action" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel("Action Description").fill("My unsaved investigation draft");
    const fresh = await staffTicket(page, ticket.id);
    const external = await page.request.patch(`${apiUrl}/api/tickets/${ticket.id}/actions/${action.id}`, { headers: await csrfHeaders(page), data: { ticketVersion: fresh.version, actionVersion: before[0].version, actionAt: new Date().toISOString(), description: "Changed by another session", result: "", followUpRequired: false, followUpNote: null, attachmentNotes: null } });
    expect(external.status(), await external.text()).toBe(200);
    await dialog.getByRole("button", { name: "Save action" }).click();
    await expect(dialog.getByRole("alert")).toContainText("Refresh to review the latest version");
    await expect(dialog.getByLabel("Action Description")).toHaveValue("My unsaved investigation draft");
    await screenshot(page, "actions-taken", "stale-conflict-draft-retained");
    await dialog.getByRole("button", { name: "Refresh action" }).click();
    await expect(dialog.getByRole("button", { name: "Continue with draft" })).toBeVisible();
    await expect(dialog.getByLabel("Action Description")).toHaveValue("My unsaved investigation draft");
  });
});
